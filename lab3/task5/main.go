package main

import "fmt"

func main() {
	arr := [5]int{10, 20, 30, 40, 50}

	// срез, охватывающий весь массив
	s := arr[:]
	fmt.Println("Исходный срез:", s)

	// добавление элемента в конец
	s = append(s, 60)
	fmt.Println("После добавления 60:", s)

	// удаление элемента по индексу (например, значение 30 с индексом 2)
	index := 2
	s = append(s[:index], s[index+1:]...)
	fmt.Println("После удаления элемента с индексом", index, ":", s)
}
